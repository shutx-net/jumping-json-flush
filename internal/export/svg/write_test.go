// escaped renders one string through the writer the way document text reaches
// it, and returns the text content of the element it landed in.
func escaped(t *testing.T, s string) string {
	t.Helper()
	out := writeOnly(t, Scene{Items: []Item{TextRun{Text: s}}})
	const opener, closer = ">", "</text>"
	i := strings.Index(out, "<text")
	if i < 0 {
		t.Fatalf("no <text> element in\n%s", out)
	}
	rest := out[i:]
	return rest[strings.Index(rest, opener)+len(opener) : strings.Index(rest, closer)]
}

func TestEscapeMarkupCharacters(t *testing.T) {
	tests := []struct {
		in   string
		want string
	}{
		{"a & b", "a &amp; b"},
		{"<図>", "&lt;図&gt;"},
		{`"面"`, "&#34;面&#34;"},
		{"it's", "it&#39;s"},
		{"グラフ & <図> \"面\"", "グラフ &amp; &lt;図&gt; &#34;面&#34;"},
	}

	for _, tt := range tests {
		if got := escaped(t, tt.in); got != tt.want {
			t.Errorf("%q came out as %q, want %q", tt.in, got, tt.want)
		}
	}
}

// TestEscapeTextSubstitutesInvalidRunes is the pin escape's comment describes.
//
// It asserts the half of xml.EscapeText that the doc comment does not promise:
// a rune outside XML 1.0's Char production is REPLACED by U+FFFD rather than
// passed through. That is what stops a logical name carrying U+0001 - which the
// schema permits and jjf validate accepts - from producing a file no renderer
// will parse. If a future Go release changes the substitution, this test is
// where it is reported, rather than a malformed .svg in somebody's README.
//
// U+FDD0 is in the list for the opposite reason: XML 1.0's Char production
// PERMITS the noncharacters, so a rune surviving unchanged is the check that
// EscapeText is not over-filtering and quietly damaging legal text.
func TestEscapeTextSubstitutesInvalidRunes(t *testing.T) {
	const replacement = "\uFFFD"

	tests := []struct {
		name string
		in   string
		want string
	}{
		{"U+0001, a C0 control XML 1.0 forbids", "a\u0001b", "a" + replacement + "b"},
		{"U+000B, the other forbidden control that looks like whitespace", "a\u000Bb", "a" + replacement + "b"},
		{"U+FFFE, a noncharacter Char excludes", "a\uFFFEb", "a" + replacement + "b"},
		{"U+FFFF, likewise", "a\uFFFFb", "a" + replacement + "b"},
		{"U+FDD0, a noncharacter Char permits, survives", "a\uFDD0b", "a\uFDD0b"},
		{"tab is numeric-escaped, not passed through", "a\tb", "a&#x9;b"},
		{"a newline cannot break the one-element-per-line rule", "a\nb", "a&#xA;b"},
		{"carriage return likewise", "a\rb", "a&#xD;b"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := escaped(t, tt.in); got != tt.want {
				t.Errorf("%q came out as %q, want %q", tt.in, got, tt.want)
			}
		})
	}
}

