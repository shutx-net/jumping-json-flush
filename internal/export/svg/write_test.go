func TestExportHeader(t *testing.T) {
	out := render(t, document(linked("customers")))
	lines := strings.Split(out, "\n")

	want := []string{
		`<?xml version="1.0" encoding="UTF-8"?>`,
		"<!-- Generated by jjf from a database design document. -->",
		"<!-- The JSON is the source of truth: edit it and export again, never this file. -->",
	}
	for i, line := range want {
		if i >= len(lines) {
			t.Fatalf("the output has only %d lines, want at least %d", len(lines), len(want))
		}
		if lines[i] != line {
			t.Errorf("line %d = %q, want %q", i+1, lines[i], line)
		}
	}

	// The root element carries all four attributes, in a fixed order, and the
	// viewBox starts at the origin.
	svg := lines[len(want)]
	if !strings.HasPrefix(svg, `<svg xmlns="http://www.w3.org/2000/svg" width="`) {
		t.Errorf("the root element is %q", svg)
	}
	for _, attribute := range []string{" width=\"", " height=\"", ` viewBox="0 0 `} {
		if !strings.Contains(svg, attribute) {
			t.Errorf("the root element has no %s attribute: %q", strings.TrimSpace(attribute), svg)
		}
	}

	if !strings.HasSuffix(out, "</svg>\n") || strings.HasSuffix(out, "\n\n</svg>\n") {
		t.Errorf("the output does not end with a single closing tag line:\n%q", out[max(0, len(out)-40):])
	}
}

// TestExportHeaderHasNothingNondeterministic probes for the three ways a build
// could leak into the file: a version would make two builds of jjf disagree
// about one document, a path would make the output depend on where the input
// sat, and a year is how a timestamp shows up.
func TestExportHeaderHasNothingNondeterministic(t *testing.T) {
	out := render(t, document(linked("customers")))
	prologue := strings.SplitN(out, "<svg", 2)[0]

	for _, unwanted := range []string{"jjf version", ".json", "20"} {
		if strings.Contains(prologue, unwanted) {
			t.Errorf("the prologue mentions %q, which would break determinism:\n%s", unwanted, prologue)
		}
	}
}

// TestExportNoSanitiserBait checks the output against what GitHub's SVG
// sanitiser strips (D25, D26, D27). Every one of these would look right in a
// browser and wrong in the README the diagram was made for, which is why the
// check is on the bytes rather than on the source.
func TestExportNoSanitiserBait(t *testing.T) {
	out := render(t, document(linked("customers"), linked("orders", "customers", "coupons")))

	for _, unwanted := range []string{"class=", "style=", "<style", "dominant-baseline", "<marker", "url(#"} {
		if strings.Contains(out, unwanted) {
			t.Errorf("the output contains %q, which the sanitiser strips or which needs a marker:\n%s", unwanted, out)
		}
	}
}

// TestExportBackgroundIsFirstAndOpaque pins the answer to a transparent diagram
// on a dark-mode README (D24): the first element inside <svg> is an opaque rect
// covering the whole viewBox. A theme-aware file would need a <style> block,
// which is exactly what the sanitiser removes.
func TestExportBackgroundIsFirstAndOpaque(t *testing.T) {
	out := render(t, document(linked("customers")))
	lines := strings.Split(out, "\n")

	svg := ""
	background := ""
	for i, line := range lines {
		if strings.HasPrefix(line, "<svg ") {
			svg, background = line, lines[i+1]
			break
		}
	}
	if svg == "" {
		t.Fatalf("no root element in\n%s", out)
	}

	size := svg[strings.Index(svg, `viewBox="0 0 `)+len(`viewBox="0 0 `):]
	size = size[:strings.Index(size, `"`)]
	width, height, _ := strings.Cut(size, " ")

	want := "\t<rect x=\"0\" y=\"0\" width=\"" + width + "\" height=\"" + height + "\" fill=\"" + colourPage + "\"/>"
	if background != want {
		t.Errorf("the first element is\n%s\nwant the opaque background\n%s", background, want)
	}
}

func TestExportEveryElementOnItsOwnLine(t *testing.T) {
	out := render(t, document(linked("customers"), linked("orders", "customers")))

	lines := strings.Split(strings.TrimSuffix(out, "\n"), "\n")
	if last := lines[len(lines)-1]; last != "</svg>" {
		t.Errorf("the last line is %q, want the root element's closing tag", last)
	}

	for i, line := range lines[:len(lines)-1] {
		// One OPENING tag per line. A <text> element carries its content and
		// its closing tag on the same line, which is the point: the content is
		// document text, and putting it on a line of its own would make the
		// file's whitespace part of the drawing.
		if opened := strings.Count(line, "<") - strings.Count(line, "</"); opened != 1 {
			t.Errorf("line %d opens %d element(s), want exactly one:\n%s", i+1, opened, line)
		}
	}
}

// errWriter fails every write, standing in for a full disk or a closed pipe.
type errWriter struct{ err error }

func (w errWriter) Write([]byte) (int, error) { return 0, w.err }

func TestExportWriteError(t *testing.T) {
	boom := errors.New("boom")
	err := Export(errWriter{err: boom}, document(linked("customers"), linked("orders", "customers")))

	if err == nil {
		t.Fatal("Export to a failing writer returned no error")
	}
	if !errors.Is(err, boom) {
		t.Errorf("Export error = %v, want it to wrap %v", err, boom)
	}
	if got, want := exitcode.Of(err), exitcode.OutputFailed; got != want {
		t.Errorf("exitcode.Of(err) = %d, want %d", got, want)
	}
}
