// render exports doc and returns the SVG source. The documents in this file are
// Go literals rather than fixtures: what is under test is the shape of the
// output for one document shape at a time, and a literal keeps the shape and
// the assertion next to each other. The JSON fixtures under testdata/ render
// whole documents and are frozen as goldens instead.
func render(t *testing.T, doc *model.Document) string {
	t.Helper()
	var buf bytes.Buffer
	if err := Export(&buf, doc); err != nil {
		t.Fatalf("Export: %v", err)
	}
	return buf.String()
}

// writeOnly serialises a Scene with no Document and no layout involved, which
// is the only way the seam test is allowed to reach the writer.
func writeOnly(t *testing.T, s Scene) string {
	t.Helper()
	var buf bytes.Buffer
	bw := bufio.NewWriter(&buf)
	writeScene(bw, s)
	if err := bw.Flush(); err != nil {
		t.Fatalf("flush: %v", err)
	}
	return buf.String()
}

