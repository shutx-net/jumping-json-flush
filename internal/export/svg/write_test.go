func TestFormatCoord(t *testing.T) {
	tests := []struct {
		in   Coord
		want string
	}{
		{0, "0"},
		{10, "1"},
		{1200, "120"},
		{1205, "120.5"},
		{5, "0.5"},
		{15, "1.5"},
		{-5, "-0.5"},
		{-1200, "-120"},
	}

	for _, tt := range tests {
		if got := formatCoord(tt.in); got != tt.want {
			t.Errorf("formatCoord(%d) = %q, want %q", tt.in, got, tt.want)
		}
	}
}

// TestFormatCoordIsTheOnlyDecimalPoint checks the claim formatCoord's comment
// makes, against the actual bytes of a whole rendered document: every "." in the
// file comes from a coordinate this function wrote, or from a piece of document
// text. Nothing else in the package can produce one, because there is no
// floating point in it.
func TestFormatCoordIsTheOnlyDecimalPoint(t *testing.T) {
	out := render(t, document(linked("customers"), linked("orders", "customers")))

	for _, line := range strings.Split(out, "\n") {
		// Only the item lines, which are the indented ones. The prologue's own
		// dots are in prose and a URL, and the root element's numbers are
		// pinned byte for byte by TestWriteSceneBuiltByHand.
		if !strings.HasPrefix(line, "\t") {
			continue
		}
		// Splitting on the quote puts every attribute VALUE at an odd index and
		// everything outside the quotes at an even one, so a dot in a logical
		// name - which is document text, not a number - is not examined here.
		fields := strings.Split(line, "\"")
		for i := 1; i < len(fields); i += 2 {
			// A coordinate list, or one number: every dot in it must have a
			// digit on both sides, which is what formatCoord produces and what
			// a stray %f or a truncated ".0" would not.
			for _, number := range strings.FieldsFunc(fields[i], func(r rune) bool { return r == ' ' || r == ',' }) {
				at := strings.Index(number, ".")
				if at < 0 {
					continue
				}
				if at == 0 || at == len(number)-1 || strings.Count(number, ".") != 1 {
					t.Errorf("the output holds %q, which is not a number formatCoord can produce:\n%s", number, line)
				}
			}
		}
	}
}

