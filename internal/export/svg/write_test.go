// TestWriteSceneBuiltByHand is the compiler-checked form of the claim the two
// representations exist for (D05): the writer's input is a Scene, and a Scene is
// buildable out of nothing but numbers and strings.
//
// It mentions no Document, no Geometry and no layout call, and it never will -
// the day the writer needs a row height, a rank, a cardinality or a font role
// to produce its bytes, this test cannot be written and therefore cannot
// compile. That is what a second package would have bought, without exporting
// the whole geometry model to get it.
//
// The bytes are asserted in full rather than probed, because this is also where
// the element grammar is pinned: attribute order, the dashed stroke, the omitted
// stroke on a fill-only rect, one element per line, and the trailing newline
// after </svg>.
func TestWriteSceneBuiltByHand(t *testing.T) {
	scene := Scene{
		Width:  4000,
		Height: 2000,
		Items: []Item{
			Box{Rect: Rect{W: 4000, H: 2000}, Fill: "#ffffff"},
			Box{
				Rect: Rect{X: 100, Y: 205, W: 1200, H: 400},
				Fill: "#f4f4f4", Stroke: "#9a9a9a", StrokeWidth: 10, Dash: true,
			},
			Polyline{
				Points:      []Point{{X: 1300, Y: 405}, {X: 2000, Y: 405}, {X: 2000, Y: 1005}},
				Stroke:      "#333333",
				StrokeWidth: 10,
				Fill:        "none",
			},
			Circle{Centre: Point{X: 2000, Y: 1005}, R: 30, Fill: "#ffffff", Stroke: "#333333", StrokeWidth: 10},
			TextRun{
				At: Point{X: 700, Y: 305}, Text: "顧客", Family: "'Menlo', monospace",
				Size: 120, Weight: "bold", Anchor: "middle", Fill: "#1a1a1a",
			},
			TextRun{
				At: Point{X: 160, Y: 505}, Text: "a & b < c", Family: "'Menlo', monospace",
				Size: 120, Weight: "normal", Anchor: "start", Fill: "#1a1a1a",
			},
			TextRun{
				At: Point{X: 2000, Y: 1500}, Text: "fk_orders_customer", Family: "'Menlo', monospace",
				Size: 120, Weight: "normal", Anchor: "middle", Fill: "#1a1a1a",
			},
		},
	}

	want := strings.Join([]string{
		`<?xml version="1.0" encoding="UTF-8"?>`,
		`<!-- Generated by jjf from a database design document. -->`,
		`<!-- The JSON is the source of truth: edit it and export again, never this file. -->`,
		`<svg xmlns="http://www.w3.org/2000/svg" width="400" height="200" viewBox="0 0 400 200">`,
		"\t" + `<rect x="0" y="0" width="400" height="200" fill="#ffffff"/>`,
		"\t" + `<rect x="10" y="20.5" width="120" height="40" fill="#f4f4f4" stroke="#9a9a9a" stroke-width="1" stroke-dasharray="4 4"/>`,
		"\t" + `<polyline points="130,40.5 200,40.5 200,100.5" fill="none" stroke="#333333" stroke-width="1"/>`,
		"\t" + `<circle cx="200" cy="100.5" r="3" fill="#ffffff" stroke="#333333" stroke-width="1"/>`,
		"\t" + `<text x="70" y="30.5" font-family="'Menlo', monospace" font-size="12" font-weight="bold" text-anchor="middle" fill="#1a1a1a">顧客</text>`,
		"\t" + `<text x="16" y="50.5" font-family="'Menlo', monospace" font-size="12" font-weight="normal" text-anchor="start" fill="#1a1a1a">a &amp; b &lt; c</text>`,
		"\t" + `<text x="200" y="150" font-family="'Menlo', monospace" font-size="12" font-weight="normal" text-anchor="middle" fill="#1a1a1a">fk_orders_customer</text>`,
		`</svg>`,
		"",
	}, "\n")

	if got := writeOnly(t, scene); got != want {
		t.Errorf("the writer produced\n%s\nwant\n%s", got, want)
	}
}

