// myCheck reports the preconditions that are statements about MySQL rather than
// about the document, in document order.
//
// It returns only its own findings and never calls check.Document: Check owns
// that call and concatenates, which is what keeps the two groups
// un-interleaved.
//
// The list is not pgCheck's with a different database's name in the messages,
// and M5 is why: MySQL scopes foreign key names per SCHEMA and index and
// constraint names per TABLE, which is the exact inverse of PostgreSQL. Reusing
// pgCheck's walk on the theory that being stricter than the target is safe
// would refuse a legal MySQL document and pass an illegal one at the same time.
//
// Every rule below was run against a live MySQL 8.0 before it was written here.
// The messages describe the behaviour rather than quoting an error number,
// because a number is the one part of a server message that a release may
// renumber and a reader cannot act on.
func myCheck(doc *model.Document) []check.Finding {
	var findings []check.Finding

	// tables and constraints map a name in a schema-wide namespace to a
	// description of whatever claimed it first, so that a collision can say
	// what it collided with. Both maps are only ever LOOKED UP and assigned,
	// NEVER ranged over: ranging would make the order of the findings depend
	// on Go's map iteration and destroy the determinism the goldens and the
	// CLI output rest on. The order comes from the slice walks below and from
	// nowhere else.
	//
	// Two maps rather than pgCheck's one, because MySQL has two separate
	// schema-wide namespaces rather than one shared by four kinds of object: a
	// foreign key may take a name a table already has, and does.
	tables := make(map[string]bool, len(doc.Tables))
	constraints := make(map[string]string)
	// The two "reported" sets remember the names already reported, for the
	// reason internal/check's usedNames gives: three tables sharing a name is
	// one mistake to fix, not two findings. There are two of them for the same
	// reason there are two namespaces - a document may legally call a table
	// and a foreign key by one name, and one shared set would let a collision
	// in one namespace silence a collision in the other.
	tablesReported := make(map[string]bool)
	constraintsReported := make(map[string]bool)

	for i := range doc.Tables {
		t := &doc.Tables[i]
		label := tableLabel(t.Name)

		// M5, first half - a table name is schema-wide. internal/check
		// deliberately does not report duplicate table names, so without this
		// a document naming two tables "orders" would emit CREATE TABLE twice
		// and MySQL would reject the script. Index names are absent from this
		// namespace, which is where PostgreSQL's rule and MySQL's part
		// company: two MySQL tables may each carry an ix_created, and an index
		// may even take a name a table already has.
		if t.Name != "" {
			if tables[t.Name] && !tablesReported[t.Name] {
				tablesReported[t.Name] = true
				findings = append(findings, check.Finding{
					Where:   label,
					Message: fmt.Sprintf("is the second table this document calls %q; MySQL cannot create two tables of one name in a schema", t.Name),
				})
			}
			tables[t.Name] = true
		}

		findings = append(findings, myColumnFindings(t)...)
		findings = append(findings, myKeyFindings(t)...)

		// M5, second half. A foreign key name lives in a per-DATABASE
		// namespace in InnoDB, so two tables may not both carry an fk_parent -
		// which is the inverse of PostgreSQL, where pg_constraint is unique per
		// table and internal/export/ddl/precheck_test.go's
		// TestForeignKeyNamesMayRepeatAcrossTables pins that they may.
		for _, fk := range t.ForeignKeys {
			if fk.Name == "" {
				// The schema makes foreignKeys[].name optional and MySQL
				// invents one, so several unnamed foreign keys in one document
				// are ordinary rather than a collision.
				continue
			}
			owner := "foreign key " + fk.Name + " on table " + t.Name
			prior, taken := constraints[fk.Name]
			if !taken {
				constraints[fk.Name] = owner
				continue
			}
			if constraintsReported[fk.Name] {
				continue
			}
			constraintsReported[fk.Name] = true
			findings = append(findings, check.Finding{
				Where:   label,
				Message: fmt.Sprintf("declares foreign key %q, a name already used by %s; InnoDB keeps foreign key names in one namespace per schema", fk.Name, prior),
			})
		}
	}
	return findings
}

// myColumnFindings reports what MySQL refuses about the columns of one table,
// in column order.
//
// At most one finding comes out per column, the rule internal/check's
// checkColumnDefault already follows: one authoring mistake, one finding. The
// order the four AUTO_INCREMENT rules are tried in is the order in which one
// explains the others - a second AUTO_INCREMENT column is the whole problem
// with that column, and telling its author that it also leads no key would be
// telling them to fix something they are about to delete.
func myColumnFindings(t *model.Table) []check.Finding {
	var findings []check.Finding

	// auto is the first AUTO_INCREMENT column of the table, so that the second
	// one can name it. The document's order decides which is which, exactly as
	// it decides everything else this package reports.
	auto := ""
	for j := range t.Columns {
		c := &t.Columns[j]
		label := columnLabel(c.Name, t.Name)

		if c.AutoIncrement {
			// M3, all four rules. Each is a fact about MySQL: the first two
			// are refused outright by the server, the third is refused as an
			// invalid default, and the fourth is the silent one - MySQL
			// accepts a nullable AUTO_INCREMENT column and stores it NOT NULL,
			// which is C5's argument for a column outside the primary key and
			// PostgreSQL's identity rule in another grammar.
			said := len(findings)
			switch {
			case auto != "":
				findings = append(findings, check.Finding{
					Where:   label,
					Message: fmt.Sprintf("is autoIncrement, and so is column %q on the same table; MySQL allows one AUTO_INCREMENT column per table", auto),
				})
			case c.Default != nil:
				findings = append(findings, check.Finding{
					Where:   label,
					Message: "is autoIncrement and also declares a default; MySQL refuses a default on an AUTO_INCREMENT column",
				})
			case c.Nullable:
				findings = append(findings, check.Finding{
					Where:   label,
					Message: "is autoIncrement and declared nullable; MySQL makes an AUTO_INCREMENT column NOT NULL, so the database would not match the document",
				})
			case !myLeadsAKey(t, c.Name):
				findings = append(findings, check.Finding{
					Where:   label,
					Message: "is autoIncrement and leads no key; MySQL needs it to be the first column of this table's primaryKey or of one of its uniqueKeys, and an entry in indexes cannot serve because the script creates it after the table",
				})
			}
			if auto == "" {
				auto = c.Name
			}
			if len(findings) > said {
				// One finding per column. The skip is conditional rather than
				// unconditional so that a column this block had nothing to say
				// about still reaches the check below: "at most one" is the
				// rule, not "the first branch that matches owns the column".
				continue
			}
		}

		// M8, first half. A bare VARCHAR is a syntax error rather than a
		// column of some default width, and mysqldump always writes the
		// length, so no document the importer produced can be in this state
		// and refusing costs the round trip nothing. Two type spellings and
		// not a table of every type whose parameter is mandatory: see
		// myLengthlessTypes.
		if c.Length == nil {
			name := upperASCII(c.Type)
			for _, lengthless := range myLengthlessTypes() {
				if name == lengthless {
					findings = append(findings, check.Finding{
						Where:   label,
						Message: fmt.Sprintf("declares type %q and no length; MySQL has no default length for it, so the column would be a syntax error rather than a column", c.Type),
					})
					break
				}
			}
		}
	}
	return findings
}

// myLeadsAKey reports whether column is the first column of the table's primary
// key or of one of its unique keys.
//
// indexes[] is deliberately not consulted, and neither is the index MySQL
// creates behind a foreign key. MySQL itself would accept either, but M1 puts
// every index in phase 2, so at the moment CREATE TABLE runs the only keys that
// exist are the ones the statement carries - and MySQL rejects the table before
// the index that would have justified it is created. Requiring the author to
// declare the key produces DDL that says what it means, which is the same
// argument the finding's own message makes.
func myLeadsAKey(t *model.Table, column string) bool {
	if pk := t.PrimaryKey; pk != nil && len(pk.Columns) > 0 && pk.Columns[0] == column {
		return true
	}
	for _, uk := range t.UniqueKeys {
		if len(uk.Columns) > 0 && uk.Columns[0] == column {
			return true
		}
	}
	return false
}

// myKeyFindings reports the keys of one table whose columns MySQL cannot index,
// in the order the objects appear in the JSON: the primary key, then the unique
// keys, then the indexes.
//
// M8, second half. Unlike the PostgreSQL user-defined type that is emitted and
// fails on execution, this is entirely contained in the document: the column's
// type is right there, MySQL will refuse the statement, and there is no correct
// DDL to write instead, because the prefix length or the generated column that
// would make it legal has nowhere to live in the format. AGENTS.md allows an
// exporter to check what its own target requires, which is what this is, and
// keeps the same rule out of "jjf validate", which is why it is not there.
//
// One finding per key rather than one per column: a composite key over two TEXT
// columns is one key to redesign.
func myKeyFindings(t *model.Table) []check.Finding {
	// types maps a column name to its declared type, so that a key can ask
	// about a column without walking the table again for each one. It is
	// LOOKED UP and assigned and NEVER ranged over; the order of the findings
	// comes from the key walks below.
	types := make(map[string]string, len(t.Columns))
	for j := range t.Columns {
		types[t.Columns[j].Name] = t.Columns[j].Type
	}

	// unusable finds the first column of cols that cannot be in a key. A
	// column the table does not declare is skipped in silence, because
	// internal/check's C1 has already reported it and this walk has no type to
	// judge.
	unusable := func(cols []string) (column, typeName, clause string, found bool) {
		for _, name := range cols {
			declared, ok := types[name]
			if !ok {
				continue
			}
			if clause, bad := myKeyUnusableType(upperASCII(declared)); bad {
				return name, declared, clause, true
			}
		}
		return "", "", "", false
	}

	var findings []check.Finding
	report := func(what string, cols []string) {
		column, typeName, clause, found := unusable(cols)
		if !found {
			return
		}
		findings = append(findings, check.Finding{
			Where:   tableLabel(t.Name),
			Message: fmt.Sprintf("declares %s over column %q, whose type is %s; %s", what, column, typeName, clause),
		})
	}

	if pk := t.PrimaryKey; pk != nil {
		report("a primary key", pk.Columns)
	}
	for _, uk := range t.UniqueKeys {
		report(myNamedKey("unique key", uk.Name), uk.Columns)
	}
	for _, ix := range t.Indexes {
		report(myNamedKey("index", ix.Name), ix.Columns)
	}
	return findings
}

// myNamedKey describes one key for a finding, quoting its name when it has one.
// The schema leaves uniqueKeys[].name optional, so "a unique key" has to read
// as well as `unique key "uq_user_email"` does.
//
// It carries the dialect prefix although nothing about it is MySQL-specific,
// because the rule this file's header states is about where a function lives
// rather than about what it knows: an unprefixed name in this package means
// shared by both dialects, and only text.go and typemap.go hold those.
func myNamedKey(kind, name string) string {
	if name == "" {
		return "a " + kind
	}
	return kind + " " + fmt.Sprintf("%q", name)
}
