// myTypeParamKind reports how the parameters of the type called name are
// written. name has already been upper-cased and stripped of any attribute
// suffix by myRenderType, so BIGINT UNSIGNED never reaches here and would be
// answered paramUnknown if it did.
//
// M7. It is a switch and not a package-level map, for the reason
// internal/importer/postgres/typemap.go's canonicalTypeName gives verbatim: a
// map literal at package scope is mutable state any caller could corrupt.
//
// The list is short on purpose. Choice 5 says jjf keeps no per-system type
// catalogue, so this answers one question only - which attribute the
// parentheses hold - and every name it does not list falls to paramUnknown,
// where the document's own parameters are reproduced as stated. FLOAT and
// DOUBLE are left out for exactly that reason: MySQL reads FLOAT(24) as a
// precision in bits and FLOAT(10,2) as a deprecated precision and scale, and
// reproducing what the document says is right for both.
func myTypeParamKind(name string) paramKind {
	switch name {
	// Character, binary and bit strings: the parameter is a length. TINYINT is
	// here rather than with the integers because tinyint(1) is how MySQL
	// stores a boolean, mysqldump still writes it, and
	// skills/db-design/references/types.md tells authors to write
	// "length": 1 for exactly that - so dropping it would make the workbook
	// and the DDL describe different columns.
	case "VARCHAR", "CHARACTER VARYING", "CHAR", "CHARACTER",
		"BINARY", "VARBINARY", "BIT", "TINYINT":
		return paramLength

	// Exact numerics: the parameters are a precision and a scale.
	case "DECIMAL", "DEC", "NUMERIC", "FIXED":
		return paramPrecisionScale

	// Date and time: the parameter counts fractional-second digits, and MySQL
	// spells every one of them as a single word, so there is no infix case
	// here at all. paramTimePrecisionInfix stays a PostgreSQL-only answer.
	case "DATETIME", "TIMESTAMP", "TIME":
		return paramTimePrecision

	// Types that take no parameter jjf can write. The integers are here
	// because a display width has been deprecated since MySQL 8.0.17 and
	// mysqldump no longer writes one, so emitting INT(11) would be emitting a
	// construct the server is removing. ENUM and SET are here because their
	// parenthesis holds a value list, which is not a number and which the
	// document has nowhere to keep - see M8, and myCheck's silence about it.
	case "INT", "INTEGER", "SMALLINT", "MEDIUMINT", "BIGINT",
		"BOOL", "BOOLEAN", "DATE", "YEAR",
		"TEXT", "TINYTEXT", "MEDIUMTEXT", "LONGTEXT",
		"BLOB", "TINYBLOB", "MEDIUMBLOB", "LONGBLOB",
		"JSON", "ENUM", "SET":
		return paramNone
	}
	return paramUnknown
}

// myTypeAttributes are the trailing words MySQL puts AFTER a type's
// parentheses, longest first so that the two-word form is recognised before its
// own second word is.
//
// They are the reason a MySQL type name can contain a space at all, and the
// schema's columnType pattern - ^[A-Za-z][A-Za-z0-9_ ]*$ - permits it, so
// "BIGINT UNSIGNED" is an ordinary value that a document imported from MySQL
// legitimately carries.
//
// A function returning a fresh slice rather than a package-level var, for the
// reason cmd/jjf/export.go's exportFormats gives: a package-level slice is
// mutable state any caller could corrupt. It is walked in order, never ranged
// over as a map.
func myTypeAttributes() []string {
	return []string{" UNSIGNED ZEROFILL", " UNSIGNED", " ZEROFILL"}
}

// myAttributeSuffix splits a trailing UNSIGNED, ZEROFILL or UNSIGNED ZEROFILL
// off name, returning what is left and the suffix as the document spelled it.
//
// The suffix is returned rather than normalised because choice 5 passes the
// type name through as written; only the comparison folds case, and it folds
// ASCII alone, for the reason typemap.go's upperASCII gives.
//
// A type whose whole name is an attribute keeps it: the remainder would be
// empty, which is no type at all. That is the guard pgRenderType keeps for a
// type actually called ARRAY, and it is here for the same reason.
func myAttributeSuffix(name string) (base, attr string) {
	upper := upperASCII(name)
	for _, suffix := range myTypeAttributes() {
		if len(name) > len(suffix) && strings.HasSuffix(upper, suffix) {
			return name[:len(name)-len(suffix)], name[len(name)-len(suffix):]
		}
	}
	return name, ""
}

// myRenderType folds a column's declared attributes back into its type, which
// is the reverse of what the importer took apart.
//
// M7. The parameters go BEFORE the attribute - DECIMAL(10,2) UNSIGNED, not
// DECIMAL UNSIGNED(10,2), which MySQL answers with a syntax error - so the
// attribute is split off, the parameters are rendered against what remains, and
// the attribute is put back. This is structurally the same problem
// pgInfixTimePrecision solves, approached from the other end: a parameter that
// cannot simply be appended. Saying so here is what stops a later reader taking
// one of the two for a mistake.
//
// Leaving BIGINT UNSIGNED to paramUnknown was the alternative, and it would
// reproduce whatever the document declared - which is right for a type jjf does
// not know and wrong for the one case that matters, DECIMAL UNSIGNED, where it
// would put the parenthesis after the attribute.
//
// The type NAME is passed through exactly as the document writes it and is
// never rewritten or quoted, for the reasons pgRenderType gives at length. A
// parameter a known type cannot take is dropped without a word, the same way
// and for the same reason: Export writes into an io.Writer and has no channel
// to warn on, so the documentation says it instead.
func myRenderType(c *model.Column) string {
	base, attr := myAttributeSuffix(c.Type)
	return base + typeParams(myTypeParamKind(upperASCII(base)), c) + attr
}

// myLengthlessTypes are the type names MySQL gives no default length to, so
// that a column declaring one without a length cannot be written at all.
//
// Two names and not a table of every type whose parameter is mandatory. CHAR,
// BINARY, BIT and DECIMAL all have a server default and are absent on purpose;
// ENUM and SET are absent for the opposite reason, that the document can never
// supply what they need. See M8 for why those three cases are not one case.
func myLengthlessTypes() []string { return []string{"VARCHAR", "VARBINARY"} }

// myKeyUnusableType reports why a column of the type called name cannot be part
// of a key, and whether it can be at all. name has already been upper-cased.
//
// The returned clause finishes the finding's sentence, because the two families
// fail differently and a single wording would be wrong for one of them: MySQL
// answers a TEXT or BLOB column in a key with ERROR 1170 and wants a prefix
// length, and a JSON column with ERROR 3152, which no prefix length would
// satisfy.
func myKeyUnusableType(name string) (clause string, unusable bool) {
	switch name {
	case "TEXT", "TINYTEXT", "MEDIUMTEXT", "LONGTEXT",
		"BLOB", "TINYBLOB", "MEDIUMBLOB", "LONGBLOB":
		return "MySQL refuses such a column in a key without a prefix length, which the document has nowhere to put", true
	case "JSON":
		return "MySQL indexes such a column only through a generated column on a JSON path, which the document has nowhere to express", true
	}
	return "", false
}

