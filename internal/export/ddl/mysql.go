// ---------------------------------------------------------------------------
// The MySQL dialect
// ---------------------------------------------------------------------------

// Everything MySQL alone knows lives in this file, arranged the way postgres.go
// is and for the reason its header gives: one file per dialect, so that a
// change to one dialect touches one file and a reviewer reads one dialect at a
// time. The my prefix carries the same claim the pg prefix does - a delimiter,
// a type table and a precondition are facts about a target and not about SQL.
//
// design/ddl-export.md's MySQL table is the record this file implements, and
// the comments below cite it by row: M1 for the three phases, M2 for the
// backticks, M3 for AUTO_INCREMENT, M4 for the folded comments, M5 for the
// inverted namespaces, M6 for the doubled backslash, M7 for the parameters and
// M8 for what the type name alone decides. A row and its function must move
// together; the numbers are cited so that they can be.

// ---------------------------------------------------------------------------
// Phases
// ---------------------------------------------------------------------------

// myWriteScript emits the whole script in three fixed phases: every
// CREATE TABLE, then every CREATE INDEX, then every foreign key as an
// ALTER TABLE.
//
// Three rather than PostgreSQL's four, and the missing one is not a
// simplification: MySQL has no COMMENT ON statement at all, so the fourth phase
// has nowhere to go and the two fields it carries ride on the definitions
// themselves - COMMENT on the column, COMMENT= on the table. That is M4, and
// pgHasComments' own comment says the same thing from the other side.
// Restating a column's whole definition in an ALTER TABLE ... MODIFY COLUMN was
// the alternative, and it would write one authored fact into the script twice.
//
// Everything else about choice 1 survives. Nothing in phase 1 refers to another
// table, so mutual references and self references still need no ordering and no
// cycle handling. Phase 2 still precedes phase 3, because MySQL accepts a plain
// UNIQUE INDEX as a foreign key target exactly as PostgreSQL does, so
// indexes[].unique is a legitimate source of the uniqueness a foreign key
// requires and has to exist first.
//
// The two header lines are byte for byte the ones pgWriteScript writes, and a
// test holds the two writers to agreeing. They are emitted per dialect rather
// than in Export because a dialect whose comment syntax differed would have to
// write them differently.
func myWriteScript(w *bufio.Writer, doc *model.Document) {
	io.WriteString(w, "-- Generated by jjf from a database design document.\n")
	io.WriteString(w, "-- The JSON is the source of truth: edit it and export again, never this file.\n")

	// The schema requires at least one table with at least one column, so this
	// section is never empty and needs no guard. The two below do.
	io.WriteString(w, "\n-- Tables\n\n")
	for i := range doc.Tables {
		if i > 0 {
			io.WriteString(w, "\n")
		}
		myWriteCreateTable(w, &doc.Tables[i])
	}

	if hasIndexes(doc) {
		io.WriteString(w, "\n-- Indexes\n\n")
		myWriteIndexes(w, doc)
	}
	if hasForeignKeys(doc) {
		io.WriteString(w, "\n-- Foreign keys\n\n")
		myWriteForeignKeys(w, doc)
	}
}

// ---------------------------------------------------------------------------
// Phase 1: tables
// ---------------------------------------------------------------------------

// myWriteCreateTable emits one table: every column in document order, then the
// primary key, then the unique keys, then the table's own comment after the
// closing parenthesis.
//
// Foreign keys are never inline, not even a self-reference, which is what makes
// phase 1 free of any dependency between tables. Indexes are not inline either,
// although mysqldump writes them as KEY clauses: keeping them in phase 2 is
// choice 2's rule, and the delta between the two writers stays the things that
// genuinely differ. What the round trip reads back from an inline KEY clause is
// the importer's problem and costs nothing, because the document is the same
// either way.
func myWriteCreateTable(w *bufio.Writer, t *model.Table) {
	fmt.Fprintf(w, "CREATE TABLE %s (\n", myQuoteIdent(t.Name))

	items := make([]string, 0, len(t.Columns)+1+len(t.UniqueKeys))
	for i := range t.Columns {
		items = append(items, myColumnItem(&t.Columns[i]))
	}
	if pk := t.PrimaryKey; pk != nil {
		items = append(items, constraintPrefix(myQuoteIdent, pk.Name)+"PRIMARY KEY ("+quotedList(myQuoteIdent, pk.Columns)+")")
	}
	for _, uk := range t.UniqueKeys {
		items = append(items, constraintPrefix(myQuoteIdent, uk.Name)+"UNIQUE ("+quotedList(myQuoteIdent, uk.Columns)+")")
	}

	for i, item := range items {
		io.WriteString(w, indent)
		io.WriteString(w, item)
		if i < len(items)-1 {
			io.WriteString(w, ",")
		}
		io.WriteString(w, "\n")
	}
	io.WriteString(w, ")")
	if text, ok := commentText(t.Name, t.LogicalName, t.Description); ok {
		io.WriteString(w, " COMMENT=")
		io.WriteString(w, myQuoteLiteral(text))
	}
	io.WriteString(w, ";\n")
}

// myColumnItem renders one column definition.
//
// The order is name, type, NOT NULL, DEFAULT, AUTO_INCREMENT, COMMENT, which is
// not pgColumnItem's order and is deliberately mysqldump's. The same argument
// the four-space indent rests on applies to the order of the words inside the
// line: a generated script and a dump of the database it created should read
// alike, and MySQL's column_definition grammar is less forgiving than
// PostgreSQL's about where AUTO_INCREMENT may sit, so matching the dump removes
// the question rather than answering it. Symmetry with the other writer would
// have been the alternative and is worth less than agreement with the dump this
// output is compared against twice in every round trip.
//
// NOT NULL is emitted only when the document says the column is not nullable,
// for the reason pgColumnItem gives: NULL is SQL's own default and stating it
// adds nothing.
//
// The default is copied out verbatim, with no quoting and no normalisation: the
// field is defined as SQL expression text and internal/check has already
// refused an empty one or one that does not read as an expression. A column
// carrying both a default and autoIncrement never reaches here, because myCheck
// reports it and Accept refuses the document.
func myColumnItem(c *model.Column) string {
	var b strings.Builder
	b.WriteString(myQuoteIdent(c.Name))
	b.WriteString(" ")
	b.WriteString(myRenderType(c))
	if !c.Nullable {
		b.WriteString(" NOT NULL")
	}
	if c.Default != nil {
		b.WriteString(" DEFAULT ")
		b.WriteString(*c.Default)
	}
	if c.AutoIncrement {
		b.WriteString(" AUTO_INCREMENT")
	}
	// M4: the column half of the comment fold. commentText is the shared
	// composition, so the first line is the logical name and the rest is the
	// description here exactly as it is in a COMMENT ON - which is what lets
	// the MySQL importer split an inline comment where the PostgreSQL one
	// splits a COMMENT ON.
	if text, ok := commentText(c.Name, c.LogicalName, c.Description); ok {
		b.WriteString(" COMMENT ")
		b.WriteString(myQuoteLiteral(text))
	}
	return b.String()
}

// ---------------------------------------------------------------------------
// Phase 2: indexes
// ---------------------------------------------------------------------------

// myWriteIndexes emits one statement per index, tables in document order and
// each table's indexes in document order.
func myWriteIndexes(w *bufio.Writer, doc *model.Document) {
	for i := range doc.Tables {
		t := &doc.Tables[i]
		for _, ix := range t.Indexes {
			unique := ""
			if ix.Unique {
				unique = "UNIQUE "
			}
			fmt.Fprintf(w, "CREATE %sINDEX %s ON %s (%s);\n",
				unique, myQuoteIdent(ix.Name), myQuoteIdent(t.Name), quotedList(myQuoteIdent, ix.Columns))
		}
	}
}

// ---------------------------------------------------------------------------
// Phase 3: foreign keys
// ---------------------------------------------------------------------------

// myWriteForeignKeys emits one ALTER TABLE per foreign key.
//
// The referential actions are written as the document spells them, and all five
// are legal MySQL text. Only four of them do anything: MySQL 8 accepts
// SET DEFAULT, records it and dumps it back, but InnoDB never performs the
// action and answers the delete it was supposed to handle with a foreign key
// error instead. That is drift rather than a refusal - the script is accepted,
// the document survives a round trip unchanged, and refusing it would refuse a
// document the importer can produce - and design/ddl-export.md's note under the
// MySQL table says so.
//
// ON UPDATE precedes ON DELETE, matching the field order in model.ForeignKey
// and the property order in the schema. Unlike PostgreSQL, MySQL keeps an
// explicit NO ACTION out of what it stores, so a document that states it does
// not get it back from a round trip; that is expected rather than a bug, in
// exactly the way pgWriteForeignKeys describes for its own dump tool.
func myWriteForeignKeys(w *bufio.Writer, doc *model.Document) {
	for i := range doc.Tables {
		t := &doc.Tables[i]
		for _, fk := range t.ForeignKeys {
			fmt.Fprintf(w, "ALTER TABLE %s ADD %sFOREIGN KEY (%s) REFERENCES %s (%s)",
				myQuoteIdent(t.Name), constraintPrefix(myQuoteIdent, fk.Name), quotedList(myQuoteIdent, fk.Columns),
				myQuoteIdent(fk.References.Table), quotedList(myQuoteIdent, fk.References.Columns))
			if fk.OnUpdate != "" {
				fmt.Fprintf(w, " ON UPDATE %s", fk.OnUpdate)
			}
			if fk.OnDelete != "" {
				fmt.Fprintf(w, " ON DELETE %s", fk.OnDelete)
			}
			io.WriteString(w, ";\n")
		}
	}
}

// ---------------------------------------------------------------------------
// Quoting
// ---------------------------------------------------------------------------

// myQuoteIdent writes s as a MySQL delimited identifier, always emitting the
// surrounding backticks.
//
// M2, which is choice 4's argument with a different delimiter. There is no
// exception for a name that would be legal bare: the schema's $defs/identifier
// is ^[A-Za-z_][A-Za-z0-9_]*$, so quoting is always safe, it removes the whole
// class of reserved-word collisions without a keyword list to maintain, and it
// preserves case on a server whose lower_case_table_names may be folding it.
//
// Not the double quote PostgreSQL uses: MySQL reads "order" as a string
// literal unless ANSI_QUOTES is in sql_mode, and putting it there would mean
// emitting a SET, which M6 rules out for the whole script.
//
// Doubling an embedded backtick is defensive rather than reachable - that
// pattern forbids one - and is here so that a future caller passing freer text
// cannot open a hole. The unit tests are the only place it is exercised, which
// is what text.go already says about pgQuoteIdent.
func myQuoteIdent(s string) string { return "`" + doubled(s, '`') + "`" }

// myQuoteLiteral writes s as a MySQL string literal, doubling the apostrophe
// and the backslash in one pass.
//
// M6, and the one place the two dialects' escaping genuinely differs rather
// than differing in a delimiter. MySQL treats a backslash inside a string as an
// escape character unless NO_BACKSLASH_ESCAPES is in sql_mode, which is not the
// default: 'C:\tmp' reaches the database as C: followed by a tab. This escaping
// is reachable, because it carries logicalName and description, which are free
// text in any language - a Windows path in a description is the ordinary way to
// meet it - and the failure is silent, since the script runs and stores the
// wrong text.
//
// One loop rather than two calls to doubled, for the reason doubled's own
// comment gives: chained replacements escape their own output, so doubling the
// backslash after the apostrophe would double the backslashes the first pass
// had just produced. Bytes of a multibyte UTF-8 sequence are all >= 0x80 and
// fall through untouched, so Japanese text survives unchanged.
//
// A newline is left alone, and has to be: a table comment is the logical name
// and the description joined by one, and the importer cuts it back apart at
// exactly that byte.
//
// The alternative was SET sql_mode='NO_BACKSLASH_ESCAPES' at the top of the
// script, so that PostgreSQL's rule would apply to both dialects.
// internal/export/ddl/text.go already refuses the equivalent for PostgreSQL -
// one setting invites character_set_client and time_zone after it - and a
// script that changes a session variable is a script whose effect depends on
// where it was run from.
func myQuoteLiteral(s string) string {
	var b strings.Builder
	b.Grow(len(s) + 2)
	b.WriteByte('\'')
	for i := 0; i < len(s); i++ {
		switch c := s[i]; c {
		case '\'', '\\':
			b.WriteByte(c)
			b.WriteByte(c)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('\'')
	return b.String()
}

