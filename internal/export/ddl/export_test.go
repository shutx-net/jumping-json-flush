// countingWriter records how much reached it, so that "all or nothing" can be
// asserted as the zero it is.
type countingWriter struct{ n int }

func (w *countingWriter) Write(p []byte) (int, error) { w.n += len(p); return len(p), nil }

func TestExportRefusesBeforeWriting(t *testing.T) {
	var w countingWriter

	err := Export(&w, loadDoc(t, "refused.json"))
	var re *RefusedError
	if !errors.As(err, &re) {
		t.Fatalf("Export returned %v, want a *RefusedError", err)
	}
	if w.n != 0 {
		t.Errorf("%d byte(s) were written for a refused document, want none", w.n)
	}
	if got := exitcode.Of(err); got != exitcode.InvalidInput {
		t.Errorf("exit code = %d, want %d (the document is what is wrong, not the writing)", got, exitcode.InvalidInput)
	}
}

// TestExportRefusesADocumentWithNoDialect covers the guard Export keeps for
// itself. Accept has already refused by the time the dialect is looked up, so
// this asserts the outcome a caller sees rather than which of the two guards
// produced it.
func TestExportRefusesADocumentWithNoDialect(t *testing.T) {
	var w countingWriter
	doc := loadDoc(t, "minimal.json")
	doc.Database.DBMS = model.DBMSSQLite

	err := Export(&w, doc)
	if err == nil {
		t.Fatal("Export rendered a SQLite document")
	}
	if w.n != 0 {
		t.Errorf("%d byte(s) were written, want none", w.n)
	}
}

// failingWriter fails every write, which is how the sticky-error handling of
// the bufio.Writer is reached at all.
type failingWriter struct{}

var errWriteFailed = errors.New("no space left on device")

func (failingWriter) Write([]byte) (int, error) { return 0, errWriteFailed }

func TestWriteErrorSurfaces(t *testing.T) {
	err := Export(failingWriter{}, loadDoc(t, "full.json"))
	if !errors.Is(err, errWriteFailed) {
		t.Fatalf("Export returned %v, want the write error", err)
	}
	if got := exitcode.Of(err); got != exitcode.OutputFailed {
		t.Errorf("exit code = %d, want %d (the environment stopped the write)", got, exitcode.OutputFailed)
	}
}

// Interface satisfaction, so that a signature change is a compile error here
// rather than at the call site in cmd/jjf.
var _ func(io.Writer, *model.Document) error = Export
