// TestEdgeFixtureCoversItsCases names, one by one, the awkward cases the edge
// golden is supposed to show. A regression then reports which case broke
// rather than dumping a diff of the whole file.
func TestEdgeFixtureCoversItsCases(t *testing.T) {
	src := render(t, loadDoc(t, "edge.json"))

	tests := []struct {
		name string
		want string
	}{
		{
			"a table named after the DOT keyword graph, quoted",
			"\t\"graph\" [label=<<TABLE",
		},
		{
			"a table named after the DOT keyword edge, quoted and distinct from the edge attribute statement",
			"\t\"edge\" [label=<<TABLE",
		},
		{"the graph attribute statement is still there", "\tgraph [charset=\"UTF-8\", rankdir=LR];"},
		{"the edge attribute statement is still there", "\tedge [dir=both];"},
		{"an escaped ampersand", "&amp;"},
		{"an escaped less-than", "&lt;"},
		{"an escaped greater-than", "&gt;"},
		{"an escaped double quote", "&quot;"},
		{"a Japanese logical name", "<B>辺</B>"},
		{"a column that is both a primary and a foreign key column", "<TD>PK,FK</TD>"},
		{"a precision and scale rendered into the type", "NUMERIC(5,2)"},
		{"a precision alone rendered into the type", "NUMERIC(8)"},
		{"a length winning over a precision", "NUMERIC(10)"},
		{
			"a self-referencing foreign key as a loop edge",
			"\t\"categories\" -> \"categories\" [arrowtail=crowodot, arrowhead=teetee, label=\"fk_categories_parent\"];",
		},
		{
			"a composite foreign key equal to the composite primary key, as one 1:1 edge",
			"\t\"edge_labels\" -> \"edge\" [arrowtail=teetee, arrowhead=teetee, label=\"fk_edge_labels_edge\"];",
		},
		{
			"a foreign key made unique by an index alone, also 1:1",
			"\t\"node_stats\" -> \"nodes\" [arrowtail=teetee, arrowhead=teetee, label=\"fk_node_stats_node\"];",
		},
		{
			"an unnamed foreign key labelled with its column list",
			"\t\"edge\" -> \"nodes\" [arrowtail=crowodot, arrowhead=teetee, label=\"from_node\"];",
		},
		{
			"a second foreign key between the same pair of tables",
			"\t\"edge\" -> \"nodes\" [arrowtail=crowtee, arrowhead=teetee, label=\"fk_edge_to_node\"];",
		},
		{
			"a foreign key naming a column the table does not define, which is not optional and does not crash",
			"\t\"node_stats\" -> \"graph\" [arrowtail=crowtee, arrowhead=teetee, label=\"fk_node_stats_unknown_column\"];",
		},
		{"the section comment above the stubs", "\t// referenced by a foreign key but not defined in this document"},
		{
			"a dashed stub node whose label carries the two-character DOT escape",
			`	"nodes" [shape=box, style=dashed, color="#999999", fontcolor="#999999", label="nodes\n(not defined in this document)"];`,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if !strings.Contains(src, tt.want) {
				t.Errorf("the rendered edge fixture does not contain\n\t%s\ngot:\n%s", tt.want, src)
			}
		})
	}

	// Three foreign keys name the same undefined table, and it gets one stub.
	if got := strings.Count(src, "shape=box"); got != 1 {
		t.Errorf("the output holds %d stub nodes, want 1:\n%s", got, src)
	}
}
