var update = flag.Bool("update", false, "update golden files")

// fixtures are the documents whose rendering is frozen. Between them they hold
// every shape the exporter has to survive: full.json is the ordinary document,
// edge.json the awkward ones, nofk.json the minimal output.
var fixtures = []string{"full.json", "edge.json", "nofk.json"}

// ---------------------------------------------------------------------------
// Fixtures and golden files
// ---------------------------------------------------------------------------

// loadDoc reads a fixture and decodes it. The fixture is checked against the
// schema on the way through, because a fixture that no longer conforms tests
// nothing worth knowing - and it would also be a document the CLI could never
// reach this exporter with.
func loadDoc(t *testing.T, name string) *model.Document {
	t.Helper()

	path := filepath.Join("testdata", name)
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	validator, err := schema.NewValidator()
	if err != nil {
		t.Fatal(err)
	}
	if err := validator.Validate(path, raw); err != nil {
		t.Fatalf("fixture does not conform to the schema: %v", err)
	}
	doc, err := model.Decode(raw)
	if err != nil {
		t.Fatal(err)
	}
	return doc
}

// goldenName maps a fixture name to the name of its golden file.
func goldenName(fixture string) string {
	return strings.TrimSuffix(fixture, filepath.Ext(fixture)) + ".dot"
}

func checkGolden(t *testing.T, name, have string) {
	t.Helper()
	path := filepath.Join("testdata", "golden", name)
	if *update {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(have), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read golden (run: go test ./internal/export/dot/ -update): %v", err)
	}
	if string(want) != have {
		t.Errorf("output mismatch for %s\n--- got ---\n%s\n--- want ---\n%s", name, have, want)
	}
}

func TestGolden(t *testing.T) {
	for _, name := range fixtures {
		t.Run(name, func(t *testing.T) {
			checkGolden(t, goldenName(name), render(t, loadDoc(t, name)))
		})
	}
}

// TestFixturesAreDeterministic renders each fixture twice. There are no time
// zone sub-tests as there are for the workbook: those exist because the zip
// format records local timestamps, and nothing in this package reads the clock
// at all.
func TestFixturesAreDeterministic(t *testing.T) {
	for _, name := range fixtures {
		t.Run(name, func(t *testing.T) {
			doc := loadDoc(t, name)
			if first, second := render(t, doc), render(t, doc); first != second {
				t.Errorf("two renders of %s differ:\n--- first ---\n%s\n--- second ---\n%s", name, first, second)
			}
		})
	}
}

// ---------------------------------------------------------------------------
// Structural well-formedness
// ---------------------------------------------------------------------------

// htmlLabels extracts the HTML-like label payload of every node statement.
//
// A naive scan is correct here because the emitter escapes every < and > that
// comes from document text, so the only unescaped angle brackets inside a
// label are tag delimiters, and a table node statement always ends with the
// literal </TABLE>>];.
func htmlLabels(src string) []string {
	const opener, closer = "label=<", ">];"

	var out []string
	for rest := src; ; {
		i := strings.Index(rest, opener)
		if i < 0 {
			return out
		}
		rest = rest[i+len(opener):]
		j := strings.Index(rest, closer)
		if j < 0 {
			return out
		}
		out = append(out, rest[:j])
		rest = rest[j+len(closer):]
	}
}

// TestFixturesRenderWellFormedLabels parses every label payload as XML.
//
// graphviz's HTML-like labels are XML shaped: <BR/> is self-closed, every
// attribute is quoted, and &amp; &lt; &gt; &quot; are the standard XML
// entities, so a payload that is not well-formed XML is certainly not a valid
// label. The check is NECESSARY but not sufficient - it knows nothing of
// graphviz's tag vocabulary - and it is as far as this can be taken without
// the dot binary, which this project deliberately does not require to build or
// to test.
func TestFixturesRenderWellFormedLabels(t *testing.T) {
	for _, name := range fixtures {
		t.Run(name, func(t *testing.T) {
			src := render(t, loadDoc(t, name))

			if !utf8.ValidString(src) {
				t.Fatal("the output is not valid UTF-8")
			}
			const header = "// Generated by jjf from a database design document.\n" +
				"// The JSON is the source of truth: edit it and export again, never this file.\n"
			if !strings.HasPrefix(src, header) {
				t.Errorf("the output does not open with the two comment lines:\n%.160s", src)
			}
			if !strings.HasSuffix(src, "}\n") {
				t.Errorf("the output does not end with a closing brace and one newline: %q", src[max(0, len(src)-20):])
			}

			labels := htmlLabels(src)
			if len(labels) != len(loadDoc(t, name).Tables) {
				t.Fatalf("found %d HTML labels, want one per table (%d)", len(labels), len(loadDoc(t, name).Tables))
			}
			for i, label := range labels {
				dec := xml.NewDecoder(strings.NewReader(label))
				for {
					_, err := dec.Token()
					if errors.Is(err, io.EOF) {
						break
					}
					if err != nil {
						t.Errorf("label %d is not well-formed XML: %v\n%s", i, err, label)
						break
					}
				}
			}
		})
	}
}

