func TestExportEscapesLabelText(t *testing.T) {
	// Only a logicalName or a description can carry these characters:
	// $defs/identifier and $defs/columnType forbid them.
	tbl := model.Table{
		Name:        "quotes",
		LogicalName: `A & B <c> "d"`,
		Columns: []model.Column{
			{Name: "id", LogicalName: `x < y & z`, Type: "BIGINT"},
		},
	}
	out := render(t, docOf(tbl))

	wantLine(t, out, "\t\t<TR><TD COLSPAN=\"4\" BGCOLOR=\"#e8e8e8\"><B>A &amp; B &lt;c&gt; &quot;d&quot;</B><BR/>quotes</TD></TR>")
	if strings.Contains(out, `<c>`) || strings.Contains(out, `x < y`) {
		t.Errorf("raw markup reached the label:\n%s", out)
	}
}

