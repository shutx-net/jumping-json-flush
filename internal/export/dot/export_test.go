func TestExportKeyMarkers(t *testing.T) {
	// order_lines: order_id is both a primary key and a foreign key column,
	// line_no is a primary key column alone, product_code a foreign key column
	// alone, and note neither.
	tbl := model.Table{
		Name:        "order_lines",
		LogicalName: "受注明細",
		Columns: []model.Column{
			{Name: "order_id", LogicalName: "受注ID", Type: "BIGINT"},
			{Name: "line_no", LogicalName: "行番号", Type: "SMALLINT"},
			{Name: "product_code", LogicalName: "商品コード", Type: "VARCHAR", Length: ptr(20)},
			{Name: "note", LogicalName: "備考", Type: "TEXT", Nullable: true},
		},
		PrimaryKey: &model.PrimaryKey{Columns: []string{"order_id", "line_no"}},
		ForeignKeys: []model.ForeignKey{
			{Name: "fk_order_lines_order", Columns: []string{"order_id"},
				References: model.Reference{Table: "orders", Columns: []string{"id"}}},
			{Name: "fk_order_lines_product", Columns: []string{"product_code"},
				References: model.Reference{Table: "products", Columns: []string{"code"}}},
		},
	}
	out := render(t, docOf(tbl))

	tests := []struct {
		name   string
		marker string
		column string
		typ    string
	}{
		{"a primary and foreign key column", "PK,FK", "order_id", "BIGINT"},
		{"a primary key column", "PK", "line_no", "SMALLINT"},
		{"a foreign key column", "FK", "product_code", "VARCHAR(20)"},
		{"a plain column", "", "note", "TEXT"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			wantLine(t, out, "\t\t<TR><TD>"+tt.marker+"</TD><TD ALIGN=\"LEFT\">"+tt.column+
				"</TD><TD ALIGN=\"LEFT\">"+escapeHTML(columnLogicalName(&tbl, tt.column))+
				"</TD><TD ALIGN=\"LEFT\">"+tt.typ+"</TD></TR>")
		})
	}
}

// columnLogicalName is a test-side lookup, kept out of the exporter because
// the exporter walks the columns it is printing rather than searching for one.
// It walks the slice itself rather than borrowing internal/export/erd's
// findColumn, which is unexported there and is a piece of the cardinality
// derivation rather than a lookup this package is entitled to.
func columnLogicalName(t *model.Table, column string) string {
	for i := range t.Columns {
		if t.Columns[i].Name == column {
			return t.Columns[i].LogicalName
		}
	}
	return ""
}

