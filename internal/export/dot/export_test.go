func TestExportHeader(t *testing.T) {
	out := render(t, docOf(customers()))
	lines := strings.Split(out, "\n")

	want := []string{
		"// Generated by jjf from a database design document.",
		"// The JSON is the source of truth: edit it and export again, never this file.",
		`digraph "shop" {`,
		"\tgraph [charset=\"UTF-8\", rankdir=LR];",
		"\tnode [shape=plaintext];",
		// Without dir=both graphviz draws the head arrow alone and drops the
		// crow's foot on the tail, which is the end the cardinality is on.
		"\tedge [dir=both];",
		"",
	}
	for i, line := range want {
		if i >= len(lines) {
			t.Fatalf("the output has only %d lines, want at least %d", len(lines), len(want))
		}
		if lines[i] != line {
			t.Errorf("line %d = %q, want %q", i+1, lines[i], line)
		}
	}

	// Exactly one newline after the closing brace, and no blank line before it.
	if !strings.HasSuffix(out, "}\n") || strings.HasSuffix(out, "\n\n}\n") {
		t.Errorf("the output does not end with a single closing brace line:\n%q", out[max(0, len(out)-40):])
	}

	// Nothing that would make two runs, or two builds, disagree.
	for _, unwanted := range []string{"jjf version", ".json", "20"} {
		if strings.Contains(strings.SplitN(out, "digraph", 2)[0], unwanted) {
			t.Errorf("the header mentions %q, which would break determinism:\n%s", unwanted, out)
		}
	}
}

func TestExportNodePerTable(t *testing.T) {
	doc := docOf(customers(), orders())
	out := render(t, doc)

	for _, name := range []string{"customers", "orders"} {
		wantLine(t, out, "\t\""+name+"\" [label=<<TABLE BORDER=\"0\" CELLBORDER=\"1\" CELLSPACING=\"0\" CELLPADDING=\"4\">")
	}
	// In document order.
	if first, second := strings.Index(out, `"customers" [label`), strings.Index(out, `"orders" [label`); first > second {
		t.Errorf("the nodes are not in document order:\n%s", out)
	}
	if got, want := strings.Count(out, "[label=<<TABLE"), len(doc.Tables); got != want {
		t.Errorf("the output has %d table nodes, want %d", got, want)
	}
}

// TestExportQuotesReservedNames covers the reason quoteID never omits its
// quotes: every one of these names is a DOT keyword and a legal table name.
func TestExportQuotesReservedNames(t *testing.T) {
	var tables []model.Table
	for _, name := range []string{"graph", "node", "edge", "subgraph", "strict", "digraph"} {
		tables = append(tables, model.Table{
			Name:        name,
			LogicalName: name,
			Columns:     []model.Column{{Name: "id", LogicalName: "id", Type: "BIGINT"}},
			PrimaryKey:  &model.PrimaryKey{Columns: []string{"id"}},
		})
	}
	// An edge between two of them, so both endpoints are keywords too.
	tables[1].Columns = append(tables[1].Columns, model.Column{Name: "graph_id", LogicalName: "graph_id", Type: "BIGINT"})
	tables[1].ForeignKeys = []model.ForeignKey{{
		Name:       "fk_node_graph",
		Columns:    []string{"graph_id"},
		References: model.Reference{Table: "graph", Columns: []string{"id"}},
	}}

	out := render(t, docOf(tables...))

	for _, name := range []string{"graph", "node", "edge", "subgraph", "strict", "digraph"} {
		wantLine(t, out, "\t\""+name+"\" [label=<<TABLE BORDER=\"0\" CELLBORDER=\"1\" CELLSPACING=\"0\" CELLPADDING=\"4\">")
	}
	wantLine(t, out, "\t\"node\" -> \"graph\" [arrowtail=crowodot, arrowhead=teetee, label=\"fk_node_graph\"];")
	// The quoted node statement cannot be confused with the graph attribute
	// statement a few lines above it.
	wantLine(t, out, "\tgraph [charset=\"UTF-8\", rankdir=LR];")
}

