// TestExportStubNodeForUndefinedTarget covers a legal document: the schema
// deliberately does not check that a foreign key's target exists. The edge is
// not dropped and the export does not fail; the diagram shows exactly what the
// JSON claims. "jjf validate" warns about the same document - the exporter
// never does.
func TestExportStubNodeForUndefinedTarget(t *testing.T) {
	first := model.Table{
		Name: "orders", LogicalName: "受注",
		Columns: []model.Column{{Name: "shipment_id", LogicalName: "出荷ID", Type: "BIGINT"}},
		ForeignKeys: []model.ForeignKey{{
			Name: "fk_orders_shipment", Columns: []string{"shipment_id"},
			References: model.Reference{Table: "shipments", Columns: []string{"id"}},
		}},
	}
	// A second reference to the same undefined table, from another table.
	second := model.Table{
		Name: "returns", LogicalName: "返品",
		Columns: []model.Column{{Name: "shipment_id", LogicalName: "出荷ID", Type: "BIGINT"}},
		ForeignKeys: []model.ForeignKey{{
			Name: "fk_returns_shipment", Columns: []string{"shipment_id"},
			References: model.Reference{Table: "shipments", Columns: []string{"id"}},
		}},
	}
	out := render(t, docOf(first, second))

	wantLine(t, out, "\t// referenced by a foreign key but not defined in this document")
	// The \n in the label is the two characters backslash and n, a DOT escape,
	// not a newline byte: a newline would break the one-statement-per-line
	// shape the golden files depend on.
	wantLine(t, out, `	"shipments" [shape=box, style=dashed, color="#999999", fontcolor="#999999", label="shipments\n(not defined in this document)"];`)

	if got := strings.Count(out, "shape=box"); got != 1 {
		t.Errorf("the same undefined target produced %d stubs, want 1:\n%s", got, out)
	}
	if got := strings.Count(out, " -> "); got != 2 {
		t.Errorf("the output has %d edges, want 2:\n%s", got, out)
	}
}

// TestExportUndefinedTargetsAreCaseSensitive pins that jjf folds identifier
// case nowhere: a reference to Orders in a document defining orders is an
