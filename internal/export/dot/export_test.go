// render exports doc and returns the DOT source. The documents in this file
// are Go literals rather than fixtures: what is under test is the shape of the
// output for one document shape at a time, and a literal keeps the shape and
// the assertion next to each other. The JSON fixtures render whole documents.
func render(t *testing.T, doc *model.Document) string {
	t.Helper()
	var buf bytes.Buffer
	if err := Export(&buf, doc); err != nil {
		t.Fatalf("Export: %v", err)
	}
	return buf.String()
}

// docOf wraps tables in a minimal document called shop.
func docOf(tables ...model.Table) *model.Document {
	return &model.Document{
		FormatVersion: model.CurrentFormatVersion,
		Database:      model.Database{Name: "shop"},
		Tables:        tables,
	}
}

// wantLine fails unless out holds line as a whole line.
func wantLine(t *testing.T, out, line string) {
	t.Helper()
	for _, got := range strings.Split(out, "\n") {
		if got == line {
			return
		}
	}
	t.Errorf("the output has no line\n\t%s\ngot:\n%s", line, out)
}

// wantNoLine fails when out holds line as a whole line.
func wantNoLine(t *testing.T, out, line string) {
	t.Helper()
	for _, got := range strings.Split(out, "\n") {
		if got == line {
			t.Errorf("the output has the unwanted line\n\t%s\ngot:\n%s", line, out)
			return
		}
	}
}

// customers is a table with a primary key and no foreign key.
func customers() model.Table {
	return model.Table{
		Name:        "customers",
		LogicalName: "顧客",
		Columns: []model.Column{
			{Name: "id", LogicalName: "顧客ID", Type: "BIGINT"},
			{Name: "email", LogicalName: "メールアドレス", Type: "VARCHAR", Length: ptr(255)},
		},
		PrimaryKey: &model.PrimaryKey{Name: "pk_customers", Columns: []string{"id"}},
	}
}

// orders is a child of customers through one single-column foreign key.
func orders() model.Table {
	return model.Table{
		Name:        "orders",
		LogicalName: "受注",
		Columns: []model.Column{
			{Name: "id", LogicalName: "受注ID", Type: "BIGINT"},
			{Name: "customer_id", LogicalName: "顧客ID", Type: "BIGINT"},
		},
		PrimaryKey: &model.PrimaryKey{Name: "pk_orders", Columns: []string{"id"}},
		ForeignKeys: []model.ForeignKey{{
			Name:       "fk_orders_customer",
			Columns:    []string{"customer_id"},
			References: model.Reference{Table: "customers", Columns: []string{"id"}},
		}},
	}
}

