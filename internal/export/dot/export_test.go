// TestExportDeterminism renders the same document twice. Unlike the workbook
// there are no time zone sub-tests: nothing here touches the clock, and the
// only maps in the package are looked up rather than ranged over.
func TestExportDeterminism(t *testing.T) {
	doc := docOf(customers(), orders())

	first := render(t, doc)
	for i := range 8 {
		if got := render(t, doc); got != first {
			t.Fatalf("render %d differs from the first:\n--- got ---\n%s\n--- want ---\n%s", i+2, got, first)
		}
	}
}

// errWriter fails every write, standing in for a full disk or a closed pipe.
type errWriter struct{ err error }

func (w errWriter) Write([]byte) (int, error) { return 0, w.err }

func TestExportWriteError(t *testing.T) {
	boom := errors.New("boom")
	err := Export(errWriter{err: boom}, docOf(customers(), orders()))

	if err == nil {
		t.Fatal("Export to a failing writer returned no error")
	}
	if !errors.Is(err, boom) {
		t.Errorf("Export error = %v, want it to wrap %v", err, boom)
	}
	if got, want := exitcode.Of(err), exitcode.OutputFailed; got != want {
		t.Errorf("exitcode.Of(err) = %d, want %d", got, want)
	}
}
