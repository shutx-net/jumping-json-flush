func TestParseErrors(t *testing.T) {
	tests := []struct {
		name     string
		src      string
		wantLine int
		wantMsg  string
	}{
		{
			name:     "unclosed column list",
			src:      "CREATE TABLE public.t (\n  a integer,\n  b integer\n",
			wantLine: 3,
			wantMsg:  "expected",
		},
		{
			name:     "missing ON in CREATE INDEX",
			src:      "CREATE INDEX t_a_idx public.t (a);",
			wantLine: 1,
			wantMsg:  "expected ON in CREATE INDEX",
		},
		{
			name:     "three part qualified name",
			src:      "CREATE TABLE mydb.public.t (a integer);",
			wantLine: 1,
			wantMsg:  "has too many parts",
		},
		{
			name:     "end of statement after ADD CONSTRAINT",
			src:      "ALTER TABLE public.t\n  ADD CONSTRAINT t_pkey;",
			wantLine: 2,
			wantMsg:  "expected a constraint",
		},
		{
			name:     "missing column list on a primary key",
			src:      "ALTER TABLE public.t ADD CONSTRAINT t_pkey PRIMARY KEY;",
			wantLine: 1,
			wantMsg:  `expected "("`,
		},
		{
			name:     "comment without a string",
			src:      "COMMENT ON TABLE public.t IS 42;",
			wantLine: 1,
			wantMsg:  "expected a string after IS",
		},
		{
			name:     "column definition without a type",
			src:      "CREATE TABLE public.t (\n  a,\n  b integer\n);",
			wantLine: 2,
			wantMsg:  "expected a type name",
		},
		{
			// A truncated file, which is what a dump interrupted mid-write
			// looks like. The line reported is the one the argument list
			// OPENED on rather than the end of the file, so the message points
			// at the parenthesis that was never closed.
			name:     "unterminated type argument list",
			src:      "CREATE TABLE public.t (\n  a numeric(10",
			wantLine: 2,
			wantMsg:  "unterminated type argument list",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var d diagList
			_, err := parse([]byte(tt.src), &d)
			if err == nil {
				t.Fatalf("parse(%q) returned no error, want %q", tt.src, tt.wantMsg)
			}
			var se *syntaxError
			if !errors.As(err, &se) {
				t.Fatalf("parse(%q) error type got = %T, want *syntaxError", tt.src, err)
			}
			if !strings.Contains(se.Msg, tt.wantMsg) {
				t.Errorf("parse(%q) message got = %q, want it to contain %q", tt.src, se.Msg, tt.wantMsg)
			}
			if se.Line != tt.wantLine {
				t.Errorf("parse(%q) line got = %v, want %v", tt.src, se.Line, tt.wantLine)
			}
		})
	}
}

