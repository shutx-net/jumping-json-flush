// mustParse parses src and fails the test if the dump is not well formed. The
// warnings are returned rather than asserted, because most tests care about the
// intermediate representation alone.
func mustParse(t *testing.T, src string) (*pgDump, []Diagnostic) {
	t.Helper()
	var d diagList
	dump, err := parse([]byte(src), &d)
	if err != nil {
		t.Fatalf("parse returned error %v, want no error", err)
	}
	return dump, d.all()
}

// statementHeads lexes src and returns the first token of every statement, which
// is enough to say where the splitter cut.
func statementHeads(t *testing.T, src string) []string {
	t.Helper()
	toks, err := lex([]byte(src))
	if err != nil {
		t.Fatalf("lex(%q) returned error %v, want no error", src, err)
	}
	heads := []string{}
	for _, stmt := range splitStatements(toks) {
		heads = append(heads, stmt[0].text)
	}
	return heads
}

func TestSplitStatements(t *testing.T) {
	tests := []struct {
		name string
		src  string
		want []string
	}{
		{
			name: "two statements",
			src:  "SELECT 1; SELECT 2;",
			want: []string{"select", "select"},
		},
		{
			name: "trailing statement without a semicolon",
			src:  "SELECT 1; UPDATE t SET a = 1",
			want: []string{"select", "update"},
		},
		{
			name: "empty statements are dropped",
			src:  ";;SELECT 1;;",
			want: []string{"select"},
		},
		{
			name: "semicolon inside a dollar-quoted body",
			src: "CREATE FUNCTION f() RETURNS void AS $$\nBEGIN\n  CREATE TABLE x (a int);\nEND;\n$$ LANGUAGE plpgsql;\n" +
				"SELECT 1;",
			want: []string{"create", "select"},
		},
		{
			name: "semicolon inside a string",
			src:  "INSERT INTO t VALUES (';');\nSELECT 1;",
			want: []string{"insert", "select"},
		},
		{
			name: "semicolon inside a comment",
			src:  "-- one ; two\nSELECT 1;",
			want: []string{"select"},
		},
		{
			name: "semicolon inside parentheses",
			src:  "SELECT f(a;b); SELECT 2;",
			want: []string{"select", "select"},
		},
		{
			name: "only comments",
			src:  "-- nothing here\n/* nor here */\n",
			want: []string{},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := statementHeads(t, tt.src); !slices.Equal(got, tt.want) {
				t.Errorf("splitStatements(%q) got = %v, want %v", tt.src, got, tt.want)
			}
		})
	}
}

// createTableSource exercises every column form the importer understands at
// once, in the spelling pg_dump uses.
const createTableSource = `CREATE TABLE public.users (
    id integer NOT NULL,
    email character varying(255) NOT NULL UNIQUE,
    ratio numeric(10,2) DEFAULT 1.5,
    tags text[],
    span interval day to second(6),
    created_at timestamp(3) without time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone,
    kind public.status DEFAULT 'a'::public.status,
    owner_id integer REFERENCES public.orgs(id) ON DELETE CASCADE,
    seq_id integer DEFAULT nextval('public.users_id_seq'::regclass),
    gen integer GENERATED ALWAYS AS (id + 1) STORED,
    ident integer GENERATED BY DEFAULT AS IDENTITY (INCREMENT 1 START 1),
    note text DEFAULT 'a, b (c)',
    CONSTRAINT users_pkey PRIMARY KEY (id)
);`

func TestParseCreateTable(t *testing.T) {
	dump, _ := mustParse(t, createTableSource)
	if len(dump.Tables) != 1 {
		t.Fatalf("tables got = %v, want 1", len(dump.Tables))
	}
	table := dump.Tables[0]
	if table.Name.Schema != "public" || table.Name.Name != "users" {
		t.Errorf("table name got = %v, want public.users", table.Name)
	}

	tests := []struct {
		name      string
		words     string
		args      string
		dims      int
		notNull   bool
		def       string
		identity  bool
		generated bool
	}{
		{name: "id", words: "integer", notNull: true},
		{name: "email", words: "character varying", args: "255", notNull: true},
		{name: "ratio", words: "numeric", args: "10,2", def: "1.5"},
		{name: "tags", words: "text", dims: 1},
		{name: "span", words: "interval day to second", args: "6"},
		{name: "created_at", words: "timestamp without time zone", args: "3", notNull: true, def: "now()"},
		{name: "updated_at", words: "timestamp with time zone"},
		{name: "kind", words: "public.status", def: "'a'::public.status"},
		{name: "owner_id", words: "integer"},
		{name: "seq_id", words: "integer", def: "nextval('public.users_id_seq'::regclass)"},
		{name: "gen", words: "integer", generated: true},
		{name: "ident", words: "integer", identity: true},
		{name: "note", words: "text", def: "'a, b (c)'"},
	}
	if len(table.Columns) != len(tests) {
		t.Fatalf("columns got = %v, want %v", len(table.Columns), len(tests))
	}

	for i, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			col := table.Columns[i]
			if col.Name != tt.name {
				t.Fatalf("column %d name got = %v, want %v", i, col.Name, tt.name)
			}
			if got := strings.Join(col.Type.Words, " "); got != tt.words {
				t.Errorf("%s type words got = %v, want %v", tt.name, got, tt.words)
			}
			if got := strings.Join(col.Type.Args, ","); got != tt.args {
				t.Errorf("%s type args got = %v, want %v", tt.name, got, tt.args)
			}
			if col.Type.ArrayDims != tt.dims {
				t.Errorf("%s array dimensions got = %v, want %v", tt.name, col.Type.ArrayDims, tt.dims)
			}
			if col.NotNull != tt.notNull {
				t.Errorf("%s not null got = %v, want %v", tt.name, col.NotNull, tt.notNull)
			}
			if col.HasDefault != (tt.def != "") {
				t.Errorf("%s has default got = %v, want %v", tt.name, col.HasDefault, tt.def != "")
			}
			if col.Default != tt.def {
				t.Errorf("%s default got = %q, want %q", tt.name, col.Default, tt.def)
			}
			if col.Identity != tt.identity {
				t.Errorf("%s identity got = %v, want %v", tt.name, col.Identity, tt.identity)
			}
			if col.Generated != tt.generated {
				t.Errorf("%s generated got = %v, want %v", tt.name, col.Generated, tt.generated)
			}
		})
	}

	// The inline constraints arrive in source order, ahead of the one written as
	// a table element.
	wantConstraints := []struct {
		kind    constraintKind
		name    string
		columns []string
	}{
		{kind: constraintUnique, columns: []string{"email"}},
		{kind: constraintForeign, columns: []string{"owner_id"}},
		{kind: constraintPrimaryKey, name: "users_pkey", columns: []string{"id"}},
	}
	if len(table.Constraints) != len(wantConstraints) {
		t.Fatalf("constraints got = %v, want %v", len(table.Constraints), len(wantConstraints))
	}
	for i, want := range wantConstraints {
		got := table.Constraints[i]
		if got.Kind != want.kind || got.Name != want.name || !slices.Equal(got.Columns, want.columns) {
			t.Errorf("constraint %d got = %v/%v/%v, want %v/%v/%v",
				i, got.Kind, got.Name, got.Columns, want.kind, want.name, want.columns)
		}
	}
	fk := table.Constraints[1]
	if fk.RefTable.String() != "public.orgs" || !slices.Equal(fk.RefColumns, []string{"id"}) || fk.OnDelete != "CASCADE" {
		t.Errorf("inline foreign key got = %v%v on delete %q, want public.orgs[id] on delete %q",
			fk.RefTable, fk.RefColumns, fk.OnDelete, "CASCADE")
	}
}

