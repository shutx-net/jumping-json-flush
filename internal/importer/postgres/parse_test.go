func TestParseAlterTableConstraints(t *testing.T) {
	const src = `ALTER TABLE ONLY public.t ADD CONSTRAINT t_pkey PRIMARY KEY (id);
ALTER TABLE public.t ADD CONSTRAINT t_uq UNIQUE (a, b);
ALTER TABLE ONLY public.t
    ADD CONSTRAINT t_fk FOREIGN KEY (a, b) REFERENCES public.u(x, y) ON UPDATE CASCADE ON DELETE SET NULL;
ALTER TABLE public.t ADD PRIMARY KEY (id);
ALTER TABLE IF EXISTS ONLY public.t ADD CONSTRAINT t_fk2 FOREIGN KEY (c) REFERENCES public.u;
ALTER TABLE public.t ADD CONSTRAINT t_fk3 FOREIGN KEY (d) REFERENCES public.u(x) ON DELETE RESTRICT ON UPDATE NO ACTION;
ALTER TABLE public.t ADD CONSTRAINT t_fk4 FOREIGN KEY (e) REFERENCES public.u(x) ON DELETE SET DEFAULT ON UPDATE RESTRICT;
ALTER TABLE public.t OWNER TO postgres;
ALTER TABLE ONLY public.t ALTER COLUMN id SET DEFAULT nextval('public.t_id_seq'::regclass);
ALTER TABLE public.t ALTER COLUMN a SET NOT NULL;
ALTER TABLE public.t ALTER COLUMN b DROP NOT NULL;
ALTER TABLE public.t ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY (SEQUENCE NAME public.t_id_seq START WITH 1);
ALTER TABLE public.t ALTER COLUMN a SET STATISTICS 100;`

	dump, warnings := mustParse(t, src)
	if len(warnings) != 0 {
		t.Errorf("warnings got = %v, want none", warnings)
	}

	tests := []struct {
		kind             constraintKind
		name             string
		columns          []string
		refTable         string
		refColumns       []string
		onUpdate         string
		onDelete         string
		wantNoRefColumns bool
	}{
		{kind: constraintPrimaryKey, name: "t_pkey", columns: []string{"id"}},
		{kind: constraintUnique, name: "t_uq", columns: []string{"a", "b"}},
		{
			kind: constraintForeign, name: "t_fk", columns: []string{"a", "b"},
			refTable: "public.u", refColumns: []string{"x", "y"},
			onUpdate: "CASCADE", onDelete: "SET NULL",
		},
		{kind: constraintPrimaryKey, columns: []string{"id"}},
		{
			kind: constraintForeign, name: "t_fk2", columns: []string{"c"},
			refTable: "public.u", wantNoRefColumns: true,
		},
		{
			kind: constraintForeign, name: "t_fk3", columns: []string{"d"},
			refTable: "public.u", refColumns: []string{"x"},
			onUpdate: "NO ACTION", onDelete: "RESTRICT",
		},
		{
			kind: constraintForeign, name: "t_fk4", columns: []string{"e"},
			refTable: "public.u", refColumns: []string{"x"},
			onUpdate: "RESTRICT", onDelete: "SET DEFAULT",
		},
	}
	if len(dump.Constraints) != len(tests) {
		t.Fatalf("constraints got = %v, want %v", len(dump.Constraints), len(tests))
	}
	for i, tt := range tests {
		got := dump.Constraints[i]
		if got.Kind != tt.kind || got.Name != tt.name || !slices.Equal(got.Columns, tt.columns) {
			t.Errorf("constraint %d got = %v/%v/%v, want %v/%v/%v",
				i, got.Kind, got.Name, got.Columns, tt.kind, tt.name, tt.columns)
		}
		if tt.refTable != "" && got.RefTable.String() != tt.refTable {
			t.Errorf("constraint %d references got = %v, want %v", i, got.RefTable, tt.refTable)
		}
		if tt.wantNoRefColumns && got.RefColumns != nil {
			t.Errorf("constraint %d reference columns got = %v, want none", i, got.RefColumns)
		}
		if !tt.wantNoRefColumns && tt.refColumns != nil && !slices.Equal(got.RefColumns, tt.refColumns) {
			t.Errorf("constraint %d reference columns got = %v, want %v", i, got.RefColumns, tt.refColumns)
		}
		if got.OnUpdate != tt.onUpdate || got.OnDelete != tt.onDelete {
			t.Errorf("constraint %d actions got = update %q delete %q, want update %q delete %q",
				i, got.OnUpdate, got.OnDelete, tt.onUpdate, tt.onDelete)
		}
	}

	// The foreign key statement spans two lines, so every statement after it
	// sits one line further down than its position in the list.
	wantDefault := pgDefault{
		Table:  qname{Schema: "public", Name: "t", Line: 10},
		Column: "id",
		Expr:   "nextval('public.t_id_seq'::regclass)",
		Line:   10,
	}
	if len(dump.Defaults) != 1 || dump.Defaults[0] != wantDefault {
		t.Errorf("defaults got = %v, want [%v]", dump.Defaults, wantDefault)
	}
	wantNotNulls := []pgNotNull{
		{Table: qname{Schema: "public", Name: "t", Line: 11}, Column: "a", Line: 11},
		{Table: qname{Schema: "public", Name: "t", Line: 12}, Column: "b", Drop: true, Line: 12},
	}
	if !reflect.DeepEqual(dump.NotNulls, wantNotNulls) {
		t.Errorf("not nulls got = %v, want %v", dump.NotNulls, wantNotNulls)
	}
	wantIdentities := []pgIdentity{
		{Table: qname{Schema: "public", Name: "t", Line: 13}, Column: "id", Line: 13},
	}
	if !reflect.DeepEqual(dump.Identities, wantIdentities) {
		t.Errorf("identities got = %v, want %v", dump.Identities, wantIdentities)
	}
}

func TestParseCreateIndex(t *testing.T) {
	tests := []struct {
		name        string
		src         string
		wantName    string
		wantColumns []string
		wantUnique  bool
		wantMethod  string
		wantDropped bool
	}{
		{
			name:        "plain",
			src:         "CREATE INDEX t_a_idx ON public.t USING btree (a);",
			wantName:    "t_a_idx",
			wantColumns: []string{"a"},
			wantMethod:  "btree",
		},
		{
			name:        "unique and multi column",
			src:         "CREATE UNIQUE INDEX t_ab_idx ON public.t USING btree (a, b);",
			wantName:    "t_ab_idx",
			wantColumns: []string{"a", "b"},
			wantUnique:  true,
			wantMethod:  "btree",
		},
		{
			name:        "without a method",
			src:         "CREATE INDEX t_a_idx ON public.t (a);",
			wantName:    "t_a_idx",
			wantColumns: []string{"a"},
			wantMethod:  "btree",
		},
		{
			name:        "without a name",
			src:         "CREATE INDEX ON public.t USING btree (a);",
			wantColumns: []string{"a"},
			wantMethod:  "btree",
		},
		{
			name:        "concurrently and if not exists",
			src:         "CREATE INDEX CONCURRENTLY IF NOT EXISTS t_a_idx ON ONLY public.t USING btree (a);",
			wantName:    "t_a_idx",
			wantColumns: []string{"a"},
			wantMethod:  "btree",
		},
		{
			name:        "ordering options",
			src:         "CREATE INDEX t_a_idx ON public.t USING btree (a, b DESC NULLS LAST);",
			wantName:    "t_a_idx",
			wantColumns: []string{"a", "b"},
			wantMethod:  "btree",
		},
		{
			name:        "operator class",
			src:         "CREATE INDEX t_a_idx ON public.t USING btree (a varchar_pattern_ops);",
			wantName:    "t_a_idx",
			wantColumns: []string{"a"},
			wantMethod:  "btree",
		},
		{
			name:        "non-btree method",
			src:         "CREATE INDEX t_doc_idx ON public.t USING gin (doc);",
			wantName:    "t_doc_idx",
			wantColumns: []string{"doc"},
			wantMethod:  "gin",
		},
		{
			name:        "include columns",
			src:         "CREATE INDEX t_a_idx ON public.t USING btree (a) INCLUDE (b);",
			wantName:    "t_a_idx",
			wantColumns: []string{"a"},
			wantMethod:  "btree",
		},
		{
			name:        "partial",
			src:         "CREATE UNIQUE INDEX t_a_idx ON public.t USING btree (a) WHERE (deleted_at IS NULL);",
			wantName:    "t_a_idx",
			wantColumns: []string{"a"},
			wantUnique:  true,
			wantMethod:  "btree",
		},
		{
			name:        "expression index is dropped",
			src:         "CREATE INDEX t_email_idx ON public.t USING btree (lower((email)::text));",
			wantDropped: true,
		},
		{
			name:        "mixed expression index is dropped whole",
			src:         "CREATE INDEX t_mix_idx ON public.t USING btree (a, lower(b));",
			wantDropped: true,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dump, _ := mustParse(t, tt.src)
			if tt.wantDropped {
				if len(dump.Indexes) != 0 {
					t.Fatalf("indexes got = %v, want none", dump.Indexes)
				}
				return
			}
			if len(dump.Indexes) != 1 {
				t.Fatalf("indexes got = %v, want 1", len(dump.Indexes))
			}
			idx := dump.Indexes[0]
			if idx.Name != tt.wantName {
				t.Errorf("index name got = %v, want %v", idx.Name, tt.wantName)
			}
			if idx.Table.String() != "public.t" {
				t.Errorf("index table got = %v, want public.t", idx.Table)
			}
			if !slices.Equal(idx.Columns, tt.wantColumns) {
				t.Errorf("index columns got = %v, want %v", idx.Columns, tt.wantColumns)
			}
			if idx.Unique != tt.wantUnique {
				t.Errorf("index unique got = %v, want %v", idx.Unique, tt.wantUnique)
			}
			if idx.Method != tt.wantMethod {
				t.Errorf("index method got = %v, want %v", idx.Method, tt.wantMethod)
			}
		})
	}
}

